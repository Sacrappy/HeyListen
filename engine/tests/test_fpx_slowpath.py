"""(HeyListen TICK-044) The FPX slow paths with A64_FPX_SLOWPATH=1 (a64_lift.py, a64_rtgen.py), game-free: bit-exact with
the default ones.

Guest words (hand-encoded: vector FADD / FSUB / FMUL .4S and .2S, aliased registers too; scalar FADD / FSUB / FMUL /
FNMUL / FDIV / FMADD S; FMUL by element; FRECPE / FRSQRTE S and .4S) go through a64emit.translate and a64_lift.op_text
(and hot_text) once; the lifted C is compiled twice, against the default a64_fpx.h and against the one the switch writes
(the cold `_lanes` helpers' per-lane fallback with the quiet-NaN lanes; the scalar wrappers' quiet-NaN and FDIV rescues).
tests/fpx_slowpath_test.c runs both on random registers (zeros, subnormals, infinities, quiet and signalling NaNs, a
quiet NaN in lane 3 of normal values, the extreme normals, binary32 midpoints) under random FPCR (FZ, DN, the rounding
modes, other control bits) and FPSR states, and compares the whole Ctx. Then recomp_fp_estimate with the switch's fast
path against the default one (every binary32 sign, exponent and top 10 significand bits, each FPCR, twice; binary64
random). Built at -march=x86-64-v3 and -march=x86-64-v2 with the build's FP flags; the headers are made the way
tests/test_vfpx_elem.py makes them.

    python -I -B tests/test_fpx_slowpath.py [--cc clang] [--cxx clang++]

~10 s here. It has teeth (each by hand, then restored): the quiet-NaN lanes taking signalling NaNs too (`sn` forced to
0 in a64_v_qnan_lanes): mismatches at once (IOC and the NaN's priority); a64_fpx_div_inf32 without its DZC test:
mismatches (fpsr); the estimate's FRECPE fast path up to biased exponent 254 (flushed and subnormal reciprocals):
mismatches. Skipped (exit 0) on a host that is not x86-64, without a C/C++ compiler, or on a CPU without x86-64-v2.
"""
import argparse
import os
import platform
import shutil
import sys
import tempfile
import time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import test_fpx_sticky as sticky  # noqa: E402  (its compiler search, flags and header generation)

CASES, SEED = 3000000, 20261110
GUEST = (("FADD v0.4s, v1.4s, v2.4s", 0x4E22D420), ("FSUB v0.4s, v1.4s, v2.4s", 0x4EA2D420),
         ("FMUL v0.4s, v1.4s, v2.4s", 0x6E22DC20), ("FADD v0.2s, v1.2s, v2.2s", 0x0E22D420),
         ("FSUB v0.2s, v1.2s, v2.2s", 0x0EA2D420), ("FMUL v1.4s, v1.4s, v1.4s", 0x6E21DC21),
         ("FADD v1.4s, v1.4s, v2.4s", 0x4E22D421), ("FMUL v0.4s, v1.4s, v2.s[1]", 0x4FA29020),
         ("FADD s0, s1, s2", 0x1E222820), ("FSUB s0, s1, s2", 0x1E223820), ("FMUL s0, s1, s2", 0x1E220820),
         ("FNMUL s0, s1, s2", 0x1E228820), ("FDIV s0, s1, s2", 0x1E221820), ("FMADD s0, s1, s2, s3", 0x1F020C20),
         ("FRSQRTE v0.4s, v1.4s", 0x6EA1D820), ("FRECPE v0.4s, v1.4s", 0x4EA1D820), ("FRSQRTE s0, s1", 0x7EA1D820),
         ("FRECPE s0, s1", 0x5EA1D820), ("FMLA v0.4s, v1.4s, v2.4s", 0x4E22CC20), ("FMLA v0.4s, v1.4s, v2.s[1]", 0x4FA21020),
         ("FMSUB s0, s1, s2, s3", 0x1F028C20), ("FNMADD s0, s1, s2, s3", 0x1F220C20))
ESTIMATE_START = "static uint16_t recomp_est_tab[2][1024];"


def cases(a64emit, a64_lift, used):
    words = [(0x1000, w) for _, w in GUEST]
    lifted, fl = a64emit.translate(words)
    if any(fl):
        raise SystemExit("fpx slowpath: a64emit did not translate the guest words: %s" % fl)
    out = ["/* Generated by tests/test_fpx_slowpath.py: compiled once per a64_fpx.h, FN_TABLE naming the table */",
           '#include "a64.h"']
    names = []
    for i, t in enumerate(lifted):
        o = a64_lift.op_text(t, used)
        out.append("static void g%d(Ctx *__restrict c) { %s }" % (i, o))
        out.append("static void gh%d(Ctx *__restrict c) { %s }" % (i, a64_lift.hot_text(o)))
        names += [GUEST[i][0], GUEST[i][0] + " (hot)"]
    out.append("typedef void (*GuestFn)(Ctx *);")
    out.append("const GuestFn FN_TABLE[] = {%s};" % ", ".join("g%d, gh%d" % (i, i) for i in range(len(lifted))))
    out.append("#ifdef FN_NAMES")
    out.append("const char *const fn_names[] = {%s};" % ", ".join('"%s"' % n for n in names))
    out.append("const int fn_count = %d;" % len(names))
    out.append("#endif")
    text = "\n".join(out) + "\n"
    for want in ("a64_fpx_hot_fma32_fma32(", "a64_vfpx_add32(", "a64_vfpx_sub32(", "a64_vfpx_mul32(", "a64_fpx_div32_div32(", "recomp_fp_estimate("):
        if want not in text:
            raise SystemExit("fpx slowpath: no %s in the lifted cases" % want)
    return text


def generate(cxx, tmp, flags):
    dll = os.path.join(tmp, "a64emit.dll" if os.name == "nt" else "liba64emit.so")
    sticky.build([cxx, "-std=c++20", "-O0", "-shared", "-Wno-everything", "-o", dll, os.path.join(sticky.KIT, "lift", "a64emit.cpp")]
                 + flags + ([] if os.name == "nt" else ["-fPIC"]), "a64emit")
    import build_emit
    build_emit.build = lambda force=False: dll
    import a64_lift
    import a64_rtgen
    import a64emit
    used = set()
    old, new = os.path.join(tmp, "old"), os.path.join(tmp, "new")
    os.environ.pop("A64_FPX_SLOWPATH", None)
    os.environ.pop("A64_FPX_FMA3", None)
    try:
        a64_rtgen.write(old)
        os.environ["A64_FPX_SLOWPATH"] = os.environ["A64_FPX_FMA3"] = "1"
        a64_rtgen.write(new)
        del os.environ["A64_FPX_SLOWPATH"], os.environ["A64_FPX_FMA3"]
        text = cases(a64emit, a64_lift, used)
    finally:
        os.environ.pop("A64_FPX_SLOWPATH", None)
        os.environ.pop("A64_FPX_FMA3", None)
        if a64emit._lib is not None:
            import _ctypes
            (_ctypes.FreeLibrary if os.name == "nt" else _ctypes.dlclose)(a64emit._lib._handle)
            a64emit._lib = None
    used |= {("add32", "add32", 2, 2), ("sub32", "sub32", 2, 2), ("mul32", "fma32", 2, 3), ("div32", "div32", 2, 2)}
    h_old = a64_lift.fpx_header(used)
    os.environ["A64_FPX_SLOWPATH"] = "1"
    try:
        h_new = a64_lift.fpx_header(used)
    finally:
        del os.environ["A64_FPX_SLOWPATH"]
    if "TICK-044" in h_old or "TICK-044" not in h_new:
        raise SystemExit("fpx slowpath: the switch does not select the header")
    hs_old = open(os.path.join(old, "a64_suyu.h"), encoding="utf-8").read()
    hs_new = open(os.path.join(new, "a64_suyu.h"), encoding="utf-8").read()
    if hs_new == hs_old or hs_new.replace(" || RECOMP_FPX_FMA64 /* (TICK-044) */", "") != hs_old:
        raise SystemExit("fpx slowpath: a64_suyu.h: A64_FPX_SLOWPATH must leave it, A64_FPX_FMA3 change one line")
    for d, h in ((old, h_old), (new, h_new)):
        with open(os.path.join(d, "a64_fpx.h"), "w", newline="\n") as f:
            f.write(h)
        with open(os.path.join(d, "slow_cases.c"), "w", newline="\n") as f:
            f.write(text)
    # the switch's estimate, renamed, beside the default runtime
    src = open(os.path.join(new, "a64_suyu.c"), encoding="utf-8").read()
    a = src.find(ESTIMATE_START)
    b = src.find("\n}\n", src.find("uint64_t recomp_fp_estimate(", a))
    if a < 0 or b < 0 or "TICK-044" not in src[a:b]:
        raise SystemExit("fpx slowpath: the switch's recomp_fp_estimate not found")
    est = src[a:b + 3].replace("recomp_est_tab", "recomp_est_tab_new").replace("recomp_fp_estimate(", "recomp_fp_estimate_new(")
    with open(os.path.join(new, "estimate_new.c"), "w", newline="\n") as f:
        f.write('#include "a64.h"\n' + est)
    return old, new


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--cc")
    p.add_argument("--cxx")
    p.add_argument("--cases", type=int, default=CASES)
    a = p.parse_args()
    if platform.machine().lower() not in ("x86_64", "amd64"):
        print("fpx slowpath: skipped (not an x86-64 host)")
        return
    tc_flags = None
    if not os.environ.get("HOOKSHOT_MINGW") and os.name == "nt":   # (an llvm-mingw on PATH, as the tests are run here)
        w = shutil.which("clang++")
        if w and os.path.isfile(os.path.join(os.path.dirname(w), "x86_64-w64-mingw32-clang++.exe")):
            os.environ["HOOKSHOT_MINGW"] = os.path.dirname(os.path.dirname(w))
    if not a.cc and not a.cxx:
        try:
            tcc, tcxx = sticky.toolchain.find("clang", host=True), sticky.toolchain.find("clang++", host=True)
            if os.path.isfile(tcc) and os.path.isfile(tcxx):
                cc, cxx = tcc, tcxx
                tc_flags = sticky.toolchain.native_target(host=True) + sticky.toolchain.native_link(host=True)
        except Exception:
            tc_flags = None
    if tc_flags is None:
        cc = sticky.compiler(a.cc, "CC", ("clang", "gcc", "cc"), "clang")
        cxx = sticky.compiler(a.cxx, "CXX", ("clang++", "g++", "c++"), "clang++")
    flags_of = (lambda tmp: tc_flags) if tc_flags is not None else (lambda tmp: sticky.target_flags(cc, tmp))
    if not cc or not cxx:
        print("fpx slowpath: skipped (no C/C++ compiler)")
        return
    t0 = time.time()
    failed, ran = [], []
    with tempfile.TemporaryDirectory(prefix="heylisten-fpx-slowpath-") as tmp:
        old, new = generate(cxx, tmp, flags_of(tmp))
        rt = "-I" + os.path.join(sticky.KIT, "rt")
        for march in ("x86-64-v3", "x86-64-v2"):
            base = [cc] + flags_of(tmp) + ["-march=" + march] + sticky.FLAGS + ["-D_CRT_SECURE_NO_WARNINGS", rt]
            objs = []
            for d, defs in ((old, ["-DFN_TABLE=fn_old", "-DFN_NAMES"]), (new, ["-DFN_TABLE=fn_new", "-Drecomp_fp_estimate=recomp_fp_estimate_new"])):
                o = os.path.join(d, "cases_%s.o" % march)
                sticky.build(base + defs + ["-I" + d, "-c", os.path.join(d, "slow_cases.c"), "-o", o], "the cases at " + march)
                objs.append(o)
            exe = os.path.join(tmp, "fpx_slowpath_test_%s.exe" % march)
            sticky.build(base + ["-I" + old, os.path.join(HERE, "fpx_slowpath_test.c"), os.path.join(old, "a64_suyu.c"),
                                 os.path.join(new, "estimate_new.c")] + objs + ["-o", exe], "the driver at " + march)
            r = sticky.run([exe, str(a.cases), str(SEED)])
            print(r.stdout.rstrip())
            if r.returncode == 3:
                print("fpx slowpath: %s skipped (this CPU is not %s)" % (march, march))
                continue
            ran.append(march)
            if r.returncode:
                failed.append(march)
    if not ran:
        print("fpx slowpath: skipped (this CPU is not x86-64-v2)")
        return
    if failed:
        raise SystemExit("fpx slowpath: FAIL (%s) in %.1f s" % (", ".join(failed), time.time() - t0))
    print("fpx slowpath: pass in %.1f s" % (time.time() - t0))


if __name__ == "__main__":
    main()
