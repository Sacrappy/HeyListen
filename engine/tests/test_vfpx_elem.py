"""(HeyListen TICK-041) The lifter's vectorized FMUL / FMLA / FMLS by element (.4S) and vector FMLA / FMLS (.4S), game-free:
bit-exact with the per-lane loops they replace.

Guest words (hand-encoded, with aliased registers too) go through a64emit.translate and a64_lift.op_text twice: as the
lifter emits them with A64_VFPX_ELEM=1 (a64_vfpx_mul32e / a64_vfpx_fma32e / a64_vfpx_fma32) and by default (the loop of
scalar helper calls), each also in its hot form (hot_text). tests/vfpx_elem_test.c runs both on random registers (zeros,
subnormals, infinities, quiet and signalling NaNs, the extreme normals, low-precision values that make binary32
midpoints) under random FPCR (FZ, DN, a rounding mode, other control bits) and FPSR states, and compares the whole Ctx.
Built at -march=x86-64-v3 (the vector fast paths) and -march=x86-64-v2 (no AVX2: every op takes the lanes), with the
build's FP flags. The headers are made the way tests/test_fpx_sticky.py makes them (a64emit built into a temporary folder).

    python -I -B tests/test_vfpx_elem.py [--cc clang] [--cxx clang++]

~5 s here. It has teeth (each by hand, then restored): a64_v_subn(w) dropped from the FMA fast path's FZ test (a
subnormal addend kept under FZ): 2144 mismatches at v3; the midpoint test dropped (`mids` forced to 0): 908 at v3. (v2
passes both: without AVX2 every FMLA takes the lanes.) The compilers are the build's own host toolchain when
HOOKSHOT_MINGW gives one (or an llvm-mingw first on PATH), else as test_fpx_sticky.py finds them.

Skipped (exit 0) on a host that is not x86-64, without a C/C++ compiler, or on a CPU without x86-64-v2.
"""
import argparse
import os
import platform
import shutil
import sys
import tempfile
import time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import test_fpx_sticky as sticky  # noqa: E402  (its compiler search, flags and header generation)

CASES, SEED = 3000000, 20261110
# (name, word): index 1 is L=1 (bit 21), index 3 is H=1 and L=1
GUEST = (("FMUL v0.4s, v1.4s, v2.s[1]", 0x4FA29020), ("FMLA v0.4s, v1.4s, v2.s[1]", 0x4FA21020),
         ("FMLS v0.4s, v1.4s, v2.s[1]", 0x4FA25020), ("FMUL v1.4s, v1.4s, v1.s[3]", 0x4FA19821),
         ("FMLA v1.4s, v1.4s, v1.s[3]", 0x4FA11821), ("FMLA v0.4s, v1.4s, v2.4s", 0x4E22CC20),
         ("FMLS v0.4s, v1.4s, v2.4s", 0x4EA2CC20), ("FMLA v2.4s, v2.4s, v2.4s", 0x4E22CC42))


def cases(a64emit, a64_lift, used):
    words = [(0x1000, w) for _, w in GUEST]
    lifted, fl = a64emit.translate(words)
    if any(fl):
        raise SystemExit("vfpx elem: a64emit did not translate the guest words: %s" % fl)
    os.environ.pop("A64_VFPX_ELEM", None)
    old = [a64_lift.op_text(t, used) for t in lifted]
    os.environ["A64_VFPX_ELEM"] = "1"
    try:
        new = [a64_lift.op_text(t, used) for t in lifted]
    finally:
        del os.environ["A64_VFPX_ELEM"]
    out = ["/* Generated by tests/test_vfpx_elem.py */"]
    for i, (n, o) in enumerate(zip(new, old)):
        if "a64_vfpx_" not in n or "for(" not in o:
            raise SystemExit("vfpx elem: %s was not vectorized (or the old form has no loop):\n%s\n%s" % (GUEST[i][0], n, o))
        out.append("static void g_new%d(Ctx *__restrict c) { %s }" % (i, n))
        out.append("static void g_old%d(Ctx *__restrict c) { %s }" % (i, o))
        out.append("static void g_newh%d(Ctx *__restrict c) { %s }" % (i, a64_lift.hot_text(n)))
        out.append("static void g_oldh%d(Ctx *__restrict c) { %s }" % (i, a64_lift.hot_text(o)))
    out.append("static const struct { const char *name; void (*n)(Ctx *), (*o)(Ctx *), (*nh)(Ctx *), (*oh)(Ctx *); } GUEST[] = {%s};"
               % ", ".join('{"%s", g_new%d, g_old%d, g_newh%d, g_oldh%d}' % (g[0], i, i, i, i) for i, g in enumerate(GUEST)))
    return "\n".join(out) + "\n"


def generate(cxx, tmp, flags):
    dll = os.path.join(tmp, "a64emit.dll" if os.name == "nt" else "liba64emit.so")
    sticky.build([cxx, "-std=c++20", "-O0", "-shared", "-Wno-everything", "-o", dll, os.path.join(sticky.KIT, "lift", "a64emit.cpp")]
                 + flags + ([] if os.name == "nt" else ["-fPIC"]), "a64emit")
    import build_emit
    build_emit.build = lambda force=False: dll
    import a64_lift
    import a64_rtgen
    import a64emit
    used = set()
    try:
        a64_rtgen.write(tmp)
        text = cases(a64emit, a64_lift, used)
    finally:
        if a64emit._lib is not None:
            import _ctypes
            (_ctypes.FreeLibrary if os.name == "nt" else _ctypes.dlclose)(a64emit._lib._handle)
            a64emit._lib = None
    with open(os.path.join(tmp, "vfpx_elem_cases.h"), "w", newline="\n") as f:
        f.write(text)
    with open(os.path.join(tmp, "a64_fpx.h"), "w", newline="\n") as f:
        os.environ["A64_VFPX_ELEM"] = "1"   # (the header with the vector helpers, as a lift with the switch writes it)
        try:
            f.write(a64_lift.fpx_header(used | {("mul32", "fma32", 2, 3), ("fma32", "fma32", 3, 3)}))
        finally:
            del os.environ["A64_VFPX_ELEM"]


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--cc")
    p.add_argument("--cxx")
    a = p.parse_args()
    if platform.machine().lower() not in ("x86_64", "amd64"):
        print("vfpx elem: skipped (not an x86-64 host)")
        return
    # (the build's own host toolchain first, when it is there (HOOKSHOT_MINGW / the builder's tools): a clang on PATH may
    # target MSVC without its C++ library, which a64emit.cpp needs; else as test_fpx_sticky.py finds one)
    tc_flags = None
    if not os.environ.get("HOOKSHOT_MINGW") and os.name == "nt":   # (an llvm-mingw on PATH, as the tests are run here)
        w = shutil.which("clang++")
        if w and os.path.isfile(os.path.join(os.path.dirname(w), "x86_64-w64-mingw32-clang++.exe")):
            os.environ["HOOKSHOT_MINGW"] = os.path.dirname(os.path.dirname(w))
    if not a.cc and not a.cxx:
        try:
            tcc, tcxx = sticky.toolchain.find("clang", host=True), sticky.toolchain.find("clang++", host=True)
            if os.path.isfile(tcc) and os.path.isfile(tcxx):
                cc, cxx = tcc, tcxx
                tc_flags = sticky.toolchain.native_target(host=True) + sticky.toolchain.native_link(host=True)
        except Exception:
            tc_flags = None
    if tc_flags is None:
        cc = sticky.compiler(a.cc, "CC", ("clang", "gcc", "cc"), "clang")
        cxx = sticky.compiler(a.cxx, "CXX", ("clang++", "g++", "c++"), "clang++")
    flags_of = (lambda tmp: tc_flags) if tc_flags is not None else (lambda tmp: sticky.target_flags(cc, tmp))
    if not cc or not cxx:
        print("vfpx elem: skipped (no C/C++ compiler)")
        return
    t0 = time.time()
    failed, ran = [], []
    with tempfile.TemporaryDirectory(prefix="hookshot-vfpx-elem-") as tmp:
        generate(cxx, tmp, flags_of(tmp))
        for march in ("x86-64-v3", "x86-64-v2"):
            exe = os.path.join(tmp, "vfpx_elem_test_%s.exe" % march)
            sticky.build([cc] + flags_of(tmp) + ["-march=" + march] + sticky.FLAGS +
                         ["-D_CRT_SECURE_NO_WARNINGS", "-I" + os.path.join(sticky.KIT, "rt"), "-I" + tmp,
                          os.path.join(HERE, "vfpx_elem_test.c"), os.path.join(tmp, "a64_suyu.c"), "-o", exe], "the driver at " + march)
            r = sticky.run([exe, str(CASES), str(SEED)])
            print(r.stdout.rstrip())
            if r.returncode == 3:
                print("vfpx elem: %s skipped (this CPU is not %s)" % (march, march))
                continue
            ran.append(march)
            if r.returncode:
                failed.append(march)
    if not ran:
        print("vfpx elem: skipped (this CPU is not x86-64-v2)")
        return
    if failed:
        raise SystemExit("vfpx elem: FAIL (%s) in %.1f s" % (", ".join(failed), time.time() - t0))
    print("vfpx elem: pass in %.1f s" % (time.time() - t0))


if __name__ == "__main__":
    main()
